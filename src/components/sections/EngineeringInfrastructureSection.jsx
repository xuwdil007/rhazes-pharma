export function EngineeringInfrastructureSection() {
  const [activeSystem, setActiveSystem] = useState(null);

  useEffect(() => {
    if (!activeSystem) return undefined;

    const closeOnEscape = (event) => {
      if (event.key === "Escape") setActiveSystem(null);
    };

    document.body.style.overflow = "hidden";
    window.addEventListener("keydown", closeOnEscape);
    return () => {
      document.body.style.overflow = "";
      window.removeEventListener("keydown", closeOnEscape);
    };
  }, [activeSystem]);

  return (
    <>
      <section className="engineering">
        <div className="eng-photo">
          <img
            data-cms-image="Фото раздела «Производство»"
            src={`${import.meta.env.BASE_URL}assets/engineering-infrastructure.png`}
            alt="Инженерные системы фармацевтического производства"
          />
        </div>
        <div>
          <Eyebrow>Инженерная инфраструктура</Eyebrow>
          <h2>
            Среда под <em>полным контролем</em>
          </h2>
          <p>
            В «РАЗЕС ФАРМА» инженерные системы объединены в единую архитектуру
            качества. Нажмите на пункт, чтобы посмотреть подробную информацию.
          </p>
          <ul>
            {systems.map((system) => {
              const Icon = system.icon;
              return (
                <li key={system.id}>
                  <button
                    className="engineering-system-trigger"
                    type="button"
                    onClick={() => setActiveSystem(system)}
                  >
                    <Icon />
                    <span>{system.title}</span>
                    <ArrowRight className="engineering-system-arrow" />
                  </button>
                </li>
              );
            })}
          </ul>
        </div>
      </section>

      {systems.map((system) => {
        const Icon = system.icon;
        const isOpen = activeSystem?.id === system.id;
        return (
          <div
            className="engineering-modal-backdrop"
            role="presentation"
            data-cms-block
            data-cms-name={`Инженерная система — ${system.shortTitle}`}
            hidden={!isOpen}
            key={system.id}
            onMouseDown={(event) => {
              if (event.target === event.currentTarget) setActiveSystem(null);
            }}
          >
            <article
              className="engineering-system-modal"
              role="dialog"
              aria-modal="true"
              aria-labelledby={`${system.id}-title`}
            >
              <button
                className="engineering-modal-close"
                type="button"
                aria-label="Закрыть окно"
                onClick={() => setActiveSystem(null)}
              >
                <X />
              </button>
              <header>
                <Icon />
                <div>
                  <small>Инженерная инфраструктура</small>
                  <h2 id={`${system.id}-title`}>{system.shortTitle}</h2>
                </div>
              </header>
              <p className="engineering-modal-intro">{system.intro}</p>
              <div className="engineering-modal-grid">
                {system.sections.map((section, index) => (
                  <section key={section.title}>
                    <small>{String(index + 1).padStart(2, "0")}</small>
                    <h3>{section.title}</h3>
                    {section.text && <p>{section.text}</p>}
                    {section.items && (
                      <ul>
                        {section.items.map((item) => (
                          <li key={item}>{item}</li>
                        ))}
                      </ul>
                    )}
                  </section>
                ))}
              </div>
            </article>
          </div>
        );
      })}
    </>
  );
}
